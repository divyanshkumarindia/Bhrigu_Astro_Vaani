// Word Document Export
export const exportBusinessWord = async (
  data: BusinessWordExportData,
  language: 'en' | 'hi'
): Promise<boolean> => {
  try {
    const t = (en: string, hi: string) => language === 'hi' ? hi : en;
    
    const createSectionHeader = (text: string) => new Paragraph({
      children: [
        new TextRun({
          text: text,
          bold: true,
          size: 28,
          color: '581c87',
        }),
      ],
      heading: HeadingLevel.HEADING_1,
      spacing: { before: 400, after: 200 },
      border: {
        bottom: { style: BorderStyle.SINGLE, size: 6, color: '7c3aed' },
      },
    });

    const createSubHeader = (text: string) => new Paragraph({
      children: [
        new TextRun({
          text: text,
          bold: true,
          size: 24,
          color: '059669',
        }),
      ],
      heading: HeadingLevel.HEADING_2,
      spacing: { before: 300, after: 150 },
    });

    const createLabelValue = (label: string, value: string) => new Paragraph({
      children: [
        new TextRun({ text: `${label}: `, bold: true, size: 22 }),
        new TextRun({ text: value, size: 22 }),
      ],
      spacing: { before: 80, after: 80 },
    });

    const createBulletPoint = (text: string) => new Paragraph({
      children: [new TextRun({ text: `• ${text}`, size: 22 })],
      spacing: { before: 60, after: 60 },
      indent: { left: 360 },
    });

    const doc = new Document({
      sections: [{
        properties: {},
        children: [
          // Title
          new Paragraph({
            children: [
              new TextRun({
                text: t('COMPLETE BUSINESS REPORT', 'संपूर्ण व्यापार रिपोर्ट'),
                bold: true,
                size: 40,
                color: '581c87',
              }),
            ],
            alignment: AlignmentType.CENTER,
            spacing: { after: 200 },
          }),
          new Paragraph({
            children: [
              new TextRun({
                text: t("Based on R.G. Rao's Bhrighu Nandi Nadi", "R.G. राव की भृगु नंदी नाड़ी पर आधारित"),
                size: 22,
                italics: true,
                color: '6b7280',
              }),
            ],
            alignment: AlignmentType.CENTER,
            spacing: { after: 400 },
          }),
          new Paragraph({
            children: [
              new TextRun({ text: t('Prepared for: ', 'के लिए तैयार: '), size: 24 }),
              new TextRun({ text: data.nativeName, bold: true, size: 28, color: '581c87' }),
            ],
            alignment: AlignmentType.CENTER,
            spacing: { after: 600 },
          }),

          // Business Profile Section
          createSectionHeader(t('Business Profile', 'व्यापार प्रोफ़ाइल')),
          createLabelValue(t('Business Score', 'व्यापार स्कोर'), `${data.businessScore}/100`),
          createLabelValue(t('Recommended Type', 'अनुशंसित प्रकार'), data.businessSuitability),
          createLabelValue(t('Financial Potential', 'वित्तीय संभावना'), data.financialPotential),
          createLabelValue(t('Risk Profile', 'जोखिम प्रोफ़ाइल'), data.riskTolerance),
          createLabelValue(t('Business Timing', 'व्यापार समय'), data.businessTiming),

          // House Analysis
          createSectionHeader(t('House Analysis', 'भाव विश्लेषण')),
          createLabelValue(t('10th House (Karma)', '10वां भाव (कर्म)'), `${data.tenthHouseSign} - Lord: ${data.tenthHouseLord}`),
          createLabelValue(t('Planets in 10th', '10वें भाव में ग्रह'), data.planetsIn10th.length > 0 ? data.planetsIn10th.join(', ') : t('None', 'कोई नहीं')),
          createLabelValue(t('7th House (Partnership)', '7वां भाव (साझेदारी)'), data.seventhHouseSign),
          createLabelValue(t('Planets in 7th', '7वें भाव में ग्रह'), data.planetsIn7th.length > 0 ? data.planetsIn7th.join(', ') : t('None', 'कोई नहीं')),
          new Paragraph({
            children: [new TextRun({ text: '\n' + data.partnershipCompatibility, size: 22 })],
            spacing: { before: 100, after: 200 },
          }),

          // Yog Summary
          createSectionHeader(t('Business Yog Summary', 'व्यापार योग सारांश')),
          createLabelValue(t('Sole Proprietorship Yogs', 'एकल स्वामित्व योग'), `${data.activeSoleYogsCount} ${t('Active', 'सक्रिय')}`),
          createLabelValue(t('Partnership Yogs', 'साझेदारी योग'), `${data.activePartnershipYogsCount} ${t('Active', 'सक्रिय')}`),
          createLabelValue(t('Business Field Yogs', 'व्यापार क्षेत्र योग'), `${data.activeFieldYogsCount} ${t('Active', 'सक्रिय')}`),

          // Top Business Fields
          createSubHeader(t('Recommended Industries', 'अनुशंसित उद्योग')),
          ...data.topBusinessFields.map(field => createBulletPoint(field)),

          // Active Yogs Details
          ...(data.soleYogs.length > 0 ? [
            createSubHeader(t('Active Sole Proprietorship Yogs', 'सक्रिय एकल स्वामित्व योग')),
            ...data.soleYogs.flatMap(yog => [
              new Paragraph({
                children: [new TextRun({ text: `✓ ${yog.name}`, bold: true, size: 22, color: 'f97316' })],
                spacing: { before: 100 },
              }),
              new Paragraph({
                children: [new TextRun({ text: yog.description, size: 20, italics: true })],
                spacing: { after: 100 },
                indent: { left: 360 },
              }),
            ]),
          ] : []),

          ...(data.partnershipYogs.length > 0 ? [
            createSubHeader(t('Active Partnership Yogs', 'सक्रिय साझेदारी योग')),
            ...data.partnershipYogs.flatMap(yog => [
              new Paragraph({
                children: [new TextRun({ text: `✓ ${yog.name}`, bold: true, size: 22, color: '3b82f6' })],
                spacing: { before: 100 },
              }),
              new Paragraph({
                children: [new TextRun({ text: yog.description, size: 20, italics: true })],
                spacing: { after: 100 },
                indent: { left: 360 },
              }),
            ]),
          ] : []),

          // Remedies
          ...(data.remedies.length > 0 ? [
            createSectionHeader(t('Business Remedies', 'व्यापार उपाय')),
            ...data.remedies.flatMap(remedy => [
              new Paragraph({
                children: [new TextRun({ text: `${remedy.planet}`, bold: true, size: 24, color: '059669' })],
                spacing: { before: 200 },
              }),
              createLabelValue(t('Beej Mantra', 'बीज मंत्र'), remedy.mantra),
              createLabelValue(t('Donation', 'दान'), remedy.donation),
            ]),
          ] : []),

          // Disclaimer
          new Paragraph({
            children: [new TextRun({ text: '\n\n' })],
          }),
          createSectionHeader(t('Important Notes', 'महत्वपूर्ण टिप्पणियाँ')),
          new Paragraph({
            children: [
              new TextRun({
                text: t(
                  'This report is based on Vedic astrology principles and should be used for guidance only. Business success depends on multiple factors including efforts, market conditions, and divine grace. Please consult qualified professionals for important business decisions.',
                  'यह रिपोर्ट वैदिक ज्योतिष सिद्धांतों पर आधारित है और केवल मार्गदर्शन के लिए उपयोग की जानी चाहिए। व्यापार की सफलता प्रयासों, बाजार की स्थितियों और दैवी कृपा सहित कई कारकों पर निर्भर करती है। महत्वपूर्ण व्यापार निर्णयों के लिए कृपया योग्य पेशेवरों से परामर्श करें।'
                ),
                size: 20,
                italics: true,
                color: '6b7280',
              }),
            ],
            spacing: { before: 200, after: 400 },
          }),

          // Footer
          new Paragraph({
            children: [
              new TextRun({
                text: t('Generated by Jyoti Stellar Compass', 'ज्योति स्टेलर कम्पास द्वारा निर्मित'),
                size: 18,
                color: '9ca3af',
              }),
              new TextRun({ text: ' | ' }),
              new TextRun({
                text: new Date().toLocaleDateString(language === 'hi' ? 'hi-IN' : 'en-IN'),
                size: 18,
                color: '9ca3af',
              }),
            ],
            alignment: AlignmentType.CENTER,
            spacing: { before: 400 },
          }),
        ],
      }],
    });

    const blob = await Packer.toBlob(doc);
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `Complete_Business_Report_${data.nativeName.replace(/\s+/g, '_')}.docx`;
    link.click();
    URL.revokeObjectURL(url);

    return true;
  } catch (error) {
    console.error('Word export error:', error);
    return false;
  }
};

